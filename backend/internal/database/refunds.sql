-- Preserve the old refund amount and populate the new fields.
UPDATE refunds r
SET buyer_id = COALESCE(r.buyer_id, d.buyer_id),
    seller_id = COALESCE(r.seller_id, d.seller_id),
    reason_code = COALESCE(r.reason_code, d.reason_code),
    requested_amount = COALESCE(r.requested_amount, r.amount),
    approved_amount = COALESCE(
        r.approved_amount,
        CASE
            WHEN r.status IN ('processing', 'succeeded', 'failed')
            THEN r.amount
            ELSE NULL
        END
    )
FROM order_disputes d
WHERE d.id = r.dispute_id;

