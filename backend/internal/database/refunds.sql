-- Rename the previous refund table when upgrading an existing database.
DO $$
BEGIN
    IF to_regclass('refunds') IS NULL
       AND to_regclass('order_refunds') IS NOT NULL THEN
        ALTER TABLE order_refunds RENAME TO refunds;
    ELSIF to_regclass('refunds') IS NOT NULL
       AND to_regclass('order_refunds') IS NOT NULL THEN
        RAISE EXCEPTION
            'Both refunds and order_refunds exist; reconcile before migration';
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS refunds (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispute_id BIGINT NOT NULL,
    order_id INTEGER NOT NULL,
    buyer_id INTEGER,
    seller_id INTEGER,
    reason_code VARCHAR(60),
    requested_amount NUMERIC(12,2),
    approved_amount NUMERIC(12,2),
    currency VARCHAR(3) NOT NULL DEFAULT 'NGN',
    status VARCHAR(30) NOT NULL DEFAULT 'requested'
        CHECK (status IN (
            'requested',
            'processing',
            'succeeded',
            'failed',
            'requires_review'
        )),
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    reference VARCHAR(120) NOT NULL UNIQUE,
    requested_by INTEGER NOT NULL,
    approved_by INTEGER,
    approval_note TEXT,
    failure_reason TEXT,
    processed_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- Legacy provider fields retained for existing records.
    payment_id BIGINT,
    payment_method VARCHAR(20),
    amount NUMERIC(12,2),
    provider_refund_id VARCHAR(120) UNIQUE,

    CONSTRAINT fk_refund_dispute
        FOREIGN KEY (dispute_id) REFERENCES order_disputes(id) ON DELETE RESTRICT,
    CONSTRAINT fk_refund_order
        FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT,
    CONSTRAINT fk_refund_payment
        FOREIGN KEY (payment_id) REFERENCES payments(id) ON DELETE RESTRICT,
    CONSTRAINT fk_refund_requester
        FOREIGN KEY (requested_by) REFERENCES farmers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_refunds_buyer
        FOREIGN KEY (buyer_id) REFERENCES farmers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_refunds_seller
        FOREIGN KEY (seller_id) REFERENCES farmers(id) ON DELETE RESTRICT,
    CONSTRAINT fk_refunds_approver
        FOREIGN KEY (approved_by) REFERENCES farmers(id) ON DELETE RESTRICT,
    CONSTRAINT chk_refunds_requested_amount
        CHECK (requested_amount > 0),
    CONSTRAINT chk_refunds_approved_amount
        CHECK (
            approved_amount IS NULL OR
            (approved_amount > 0 AND approved_amount <= requested_amount)
        )
);

