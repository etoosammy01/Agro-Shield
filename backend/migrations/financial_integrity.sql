-- Financial integrity: shared migration for Members 3, 4 and 5.
--
-- Every statement is idempotent: safe to run on every start, on a fresh database
-- and on a database that already has the older wallet schema. Constraint changes
-- use the same guarded drop-and-re-add pattern as the existing migrations,
-- because CREATE TABLE IF NOT EXISTS never alters an existing table.
--
-- ONE migration owns the wallet_transactions type list. Two blocks that each
-- re-add that constraint with their own list would overwrite one another.

-- 1. Ledger types ---------------------------------------------------------------
--    existing: deposit, deposit_reversal, withdrawal_reserved, withdrawal_refund,
--              order_payment, sale_credit, transfer_out, transfer_in, transfer_refund
--    added (Member 5): sale_reversal  - debit of the seller's held funds
--                      order_refund   - credit to the buyer's wallet
DO $$
DECLARE
    constraint_row RECORD;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'wallet_transactions'::regclass AND contype = 'c'
          AND pg_get_constraintdef(oid) ILIKE '%order_refund%'
          AND pg_get_constraintdef(oid) ILIKE '%sale_reversal%'
    ) THEN
        FOR constraint_row IN
            SELECT conname FROM pg_constraint
            WHERE conrelid = 'wallet_transactions'::regclass AND contype = 'c'
              AND pg_get_constraintdef(oid) ILIKE '%type%'
        LOOP
            EXECUTE format('ALTER TABLE wallet_transactions DROP CONSTRAINT %I', constraint_row.conname);
        END LOOP;
        ALTER TABLE wallet_transactions ADD CONSTRAINT wallet_transactions_type_check
            CHECK (type IN ('deposit','deposit_reversal','withdrawal_reserved','withdrawal_refund',
                            'order_payment','sale_credit','transfer_out','transfer_in','transfer_refund',
                            'sale_reversal','order_refund'));
    END IF;
END $$;

-- 2. Deposit status: 'held' ----------------------------------------------------
--    A verified payment the policy would not let the wallet absorb yet (for
--    example over the balance cap, or an account that is not verified). The money
--    is at the provider; the deposit waits for release or refund.
DO $$
DECLARE
    constraint_row RECORD;
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'wallet_deposits'::regclass AND contype = 'c'
          AND pg_get_constraintdef(oid) ILIKE '%held%'
    ) THEN
        FOR constraint_row IN
            SELECT conname FROM pg_constraint
            WHERE conrelid = 'wallet_deposits'::regclass AND contype = 'c'
              AND pg_get_constraintdef(oid) ILIKE '%status%'
        LOOP
            EXECUTE format('ALTER TABLE wallet_deposits DROP CONSTRAINT %I', constraint_row.conname);
        END LOOP;
        ALTER TABLE wallet_deposits ADD CONSTRAINT wallet_deposits_status_check
            CHECK (status IN ('pending','processing','successful','failed','expired','reversed','held'));
    END IF;
END $$;

-- 3. Escrow: money the farmer sees but cannot move ----------------------------
--    wallets.balance keeps meaning "what the farmer sees". held_balance is the
--    part of it still in escrow. Spendable = balance - held_balance.
--    The CHECK makes it impossible for ANY statement, including one with a bug,
--    to take a wallet's balance below its held funds.
ALTER TABLE wallets ADD COLUMN IF NOT EXISTS held_balance NUMERIC(12,2) NOT NULL DEFAULT 0;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'wallets_held_balance_bounds') THEN
        ALTER TABLE wallets ADD CONSTRAINT wallets_held_balance_bounds
            CHECK (held_balance >= 0 AND held_balance <= balance);
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS escrow_holds (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id         BIGINT        NOT NULL,
    seller_wallet_id BIGINT        NOT NULL,
    buyer_wallet_id  BIGINT        NOT NULL,
    -- Snapshot of the order's money at the moment of payment, so a refund never
    -- depends on a commission rate that may have changed since.
    --   gross_amount      what the buyer paid
    --   commission_amount the platform's share of it (0 when commission is off)
    --   amount            the seller's net, placed in escrow (gross - commission)
    gross_amount      NUMERIC(12,2) NOT NULL CHECK (gross_amount > 0),
    commission_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (commission_amount >= 0),
    amount           NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    released_amount  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (released_amount >= 0),
    -- Refunds, in three matching totals. refunded_amount is the part taken from
    -- the seller's held funds; commission_reversed is the platform's part;
    -- refunded_gross is what buyers have received back. They always add up.
    refunded_amount  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
    commission_reversed NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (commission_reversed >= 0),
    refunded_gross   NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (refunded_gross >= 0),
    -- held: buyer has not confirmed. disputed: frozen, release blocked.
    -- closed: nothing remains in escrow.
    status           VARCHAR(10)   NOT NULL DEFAULT 'held'
                     CHECK (status IN ('held','disputed','closed')),
    closed_reason    VARCHAR(10)   CHECK (closed_reason IN ('released','refunded','split')),
    release_after    TIMESTAMP,   -- automatic release deadline; NULL until product sets one
    created_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at       TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    closed_at        TIMESTAMP,
    CONSTRAINT escrow_holds_one_per_order UNIQUE (order_id),
    CONSTRAINT escrow_holds_not_overspent CHECK (released_amount + refunded_amount <= amount),
    CONSTRAINT escrow_holds_split_adds_up CHECK (
        gross_amount = amount + commission_amount
        AND refunded_gross = refunded_amount + commission_reversed
        AND commission_reversed <= commission_amount
        AND refunded_gross <= gross_amount),
    CONSTRAINT escrow_holds_closed_is_empty CHECK (
        (status = 'closed' AND closed_reason IS NOT NULL AND closed_at IS NOT NULL
            AND released_amount + refunded_amount = amount)
        OR
        (status <> 'closed' AND closed_reason IS NULL AND closed_at IS NULL
            AND released_amount + refunded_amount < amount)
    ),
    CONSTRAINT fk_escrow_order  FOREIGN KEY (order_id)         REFERENCES orders(id)  ON DELETE RESTRICT,
    CONSTRAINT fk_escrow_seller FOREIGN KEY (seller_wallet_id) REFERENCES wallets(id) ON DELETE RESTRICT,
    CONSTRAINT fk_escrow_buyer  FOREIGN KEY (buyer_wallet_id)  REFERENCES wallets(id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_escrow_holds_open ON escrow_holds (status) WHERE status <> 'closed';
CREATE INDEX IF NOT EXISTS idx_escrow_holds_seller ON escrow_holds (seller_wallet_id);

-- Append-only audit trail. The unique key makes every step idempotent: a retried
-- release or refund inserts nothing and the caller sees it already happened.
CREATE TABLE IF NOT EXISTS escrow_events (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    escrow_hold_id BIGINT        NOT NULL,
    event          VARCHAR(20)   NOT NULL
                   CHECK (event IN ('held','released','refunded','disputed','dispute_cleared')),
    amount         NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (amount >= 0),
    -- Who did it: a farmer id, an admin id, or NULL for the system.
    actor_id       INTEGER,
    -- Caller-chosen idempotency key, e.g. 'release:order-42' or 'refund:<refund id>'.
    reference      TEXT          NOT NULL,
    detail         TEXT          NOT NULL DEFAULT '',
    created_at     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT escrow_events_idempotent UNIQUE (escrow_hold_id, event, reference),
    CONSTRAINT fk_escrow_event_hold FOREIGN KEY (escrow_hold_id) REFERENCES escrow_holds(id) ON DELETE RESTRICT
);

CREATE OR REPLACE FUNCTION forbid_row_change() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: % is not allowed', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'restrict_violation';
END;
$$ LANGUAGE plpgsql;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'escrow_events_append_only') THEN
        CREATE TRIGGER escrow_events_append_only
            BEFORE UPDATE OR DELETE ON escrow_events
            FOR EACH ROW EXECUTE FUNCTION forbid_row_change();
    END IF;
END $$;

-- 4. Payment exceptions: money the code will not move on its own --------------
--    Never resolved by an automatic debit of unrelated funds. An operator reads
--    the row, decides, and records the outcome here.
CREATE TABLE IF NOT EXISTS payment_exceptions (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind                    VARCHAR(30)  NOT NULL CHECK (kind IN (
                                'duplicate_payment',          -- second successful payment on one reference
                                'deposit_reversal_unfunded',  -- provider reversed a deposit already spent
                                'refund_unfunded',            -- refund needs funds that are no longer held
                                'held_deposit',               -- verified payment the policy would not credit
                                'amount_mismatch',            -- verified amount differs from the recorded one
                                'unknown_reference',          -- verified payment matching nothing we hold
                                'other')),
    status                  VARCHAR(15)  NOT NULL DEFAULT 'open'
                            CHECK (status IN ('open','investigating','resolved','dismissed')),
    -- What the exception is about. All optional except reference: each kind fills
    -- what it knows.
    reference               TEXT         NOT NULL,
    provider_transaction_id TEXT,
    wallet_id               BIGINT,
    order_id                BIGINT,
    refund_id               BIGINT,       -- Member 5's refund record; no FK, their table owns it
    amount                  NUMERIC(12,2) CHECK (amount IS NULL OR amount > 0),
    currency                VARCHAR(3),
    detail                  TEXT         NOT NULL DEFAULT '',
    resolution_note         TEXT         NOT NULL DEFAULT '',
    resolved_by             INTEGER,
    created_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at             TIMESTAMP,
    CONSTRAINT payment_exceptions_resolved_has_time CHECK (
        (status IN ('resolved','dismissed')) = (resolved_at IS NOT NULL)),
    CONSTRAINT fk_payment_exception_wallet FOREIGN KEY (wallet_id) REFERENCES wallets(id) ON DELETE RESTRICT
);
-- A webhook that is retried must not open a second exception for the same event:
-- insert with ON CONFLICT DO NOTHING.
CREATE UNIQUE INDEX IF NOT EXISTS payment_exceptions_dedupe
    ON payment_exceptions (kind, reference, COALESCE(provider_transaction_id, ''));
CREATE INDEX IF NOT EXISTS idx_payment_exceptions_open
    ON payment_exceptions (created_at) WHERE status IN ('open','investigating');

-- 5. Commission reversals ---------------------------------------------------------
--    platform_revenue rows must be positive, so a refunded commission is recorded
--    here instead of as a negative row. Net platform revenue for an order is its
--    platform_revenue.amount minus the sum of its reversals. Append-only.
CREATE TABLE IF NOT EXISTS platform_revenue_reversals (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   BIGINT        NOT NULL,
    refund_id  BIGINT        NOT NULL,
    amount     NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    -- 'refund:<refunds.id>': one reversal per refund, so a retry inserts nothing.
    reference  TEXT          NOT NULL,
    created_at TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT platform_revenue_reversals_idempotent UNIQUE (reference),
    CONSTRAINT fk_revenue_reversal_order FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE RESTRICT
);

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'platform_revenue_reversals_append_only') THEN
        CREATE TRIGGER platform_revenue_reversals_append_only
            BEFORE UPDATE OR DELETE ON platform_revenue_reversals
            FOR EACH ROW EXECUTE FUNCTION forbid_row_change();
    END IF;
END $$;